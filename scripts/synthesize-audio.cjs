// Original procedural audio: no samples, models, downloads, or third-party music.
const fs = require('node:fs');
const path = require('node:path');
const RATE = 22050;
const hz = midi => 440 * 2 ** ((midi - 69) / 12);
function canvas(seconds) { return new Float64Array(Math.round(seconds * RATE)); }
function tone(out, at, duration, frequency, gain = .15, kind = 'pluck') {
  const start = Math.round(at * RATE), length = Math.round(duration * RATE);
  for (let i = 0; i < length; i++) {
    const t = i / RATE, u = i / length, attack = Math.min(1, t / .008), tail = Math.min(1, (1-u) / .04);
    const decay = kind === 'bell' ? Math.exp(-t * 5) : kind === 'bass' ? Math.exp(-t * 2.6) : Math.exp(-t * 4.2);
    const wave = Math.sin(2*Math.PI*frequency*t) + .25*Math.sin(2*Math.PI*frequency*2*t)*Math.exp(-t*9) + .1*Math.sin(2*Math.PI*frequency*3*t)*Math.exp(-t*14);
    const index = (start+i) % out.length; out[index] += wave * gain * attack * tail * decay;
  }
}
function chirp(out, at, duration, from, to, gain=.07) {
  const start=Math.round(at*RATE), n=Math.round(duration*RATE);let phase=0;
  for(let i=0;i<n;i++){const u=i/n;phase+=2*Math.PI*(from+(to-from)*u)/RATE;out[(start+i)%out.length]+=Math.sin(phase)*Math.sin(Math.PI*u)**2*gain;}
}
function noise(out, gain, decay=0) {
  let state=173,low=0;
  for(let i=0;i<out.length;i++){state=(1664525*state+1013904223)>>>0;const white=state/2147483648-1;low=.87*low+.13*white;const t=i/RATE;out[i]+=(white-low)*gain*Math.min(1,t/.02)*Math.min(1,(out.length-i)/RATE/.03)*Math.exp(-decay*t);}
}
function encode(samples, peakLimit=.65) {
  let peak=0;for(const x of samples){if(!Number.isFinite(x))throw new Error('Invalid audio sample');peak=Math.max(peak,Math.abs(x));}
  const scale=peak>peakLimit?peakLimit/peak:1, buffer=Buffer.alloc(44+samples.length*2);
  buffer.write('RIFF');buffer.writeUInt32LE(buffer.length-8,4);buffer.write('WAVE',8);buffer.write('fmt ',12);buffer.writeUInt32LE(16,16);buffer.writeUInt16LE(1,20);buffer.writeUInt16LE(1,22);buffer.writeUInt32LE(RATE,24);buffer.writeUInt32LE(RATE*2,28);buffer.writeUInt16LE(2,32);buffer.writeUInt16LE(16,34);buffer.write('data',36);buffer.writeUInt32LE(samples.length*2,40);
  for(let i=0;i<samples.length;i++)buffer.writeInt16LE(Math.round(Math.max(-1,Math.min(1,samples[i]*scale))*32767),44+i*2);
  return buffer;
}
function sounds() {
  const bank={};
  const sequence=(name,notes,spacing=.09,kind='bell',duration=.7,gain=.15)=>{const out=canvas(duration);notes.forEach((note,i)=>tone(out,i*spacing,Math.max(.1,duration-i*spacing),hz(note),gain,kind));bank[name]=out;};
  sequence('click',[74],.1,'pluck',.16,.08);
  sequence('arrival',[81,86],.11,'bell',.6,.1);
  sequence('ready',[86,90,93],.1,'bell',.75,.13);
  sequence('serve',[62,69],.07,'pluck',.42,.18);
  sequence('checkout',[93,98,105],.075,'bell',.65,.10);
  sequence('warning',[65,62],.14,'pluck',.5,.07);
  sequence('growth',[62,65,69,72,77,81],.12,'pluck',1.5,.13);
  sequence('wand',[93,98,105,110],.06,'bell',.65,.075);chirp(bank.wand,.03,.24,1000,2800,.035);
  sequence('pill',[74,81,86],.09,'pluck',.65,.11);chirp(bank.pill,0,.16,220,640,.07);
  sequence('mirror',[81,86,93,98],.11,'bell',1,.075);
  sequence('donut',[65,69,74,77],.09,'pluck',.8,.12);
  sequence('bomb',[50,62,74],.1,'bass',.7,.16);noise(bank.bomb,.045,14);
  const music=canvas(24);
  const melody=[74,77,81,79,77,74,72,69,74,77,79,81,84,81,77,74,69,72,74,77,79,77,74,72,74,81,79,77,74,72,69,72];
  melody.forEach((note,i)=>{tone(music,i*.75,2,hz(note),.09);tone(music,i*.75+.065,1.65,hz(note),.025);});
  [50,53,48,57,50,53].forEach((base,i)=>{tone(music,i*4,3.8,hz(base),.09,'bass');tone(music,i*4+2,2,hz(base+7),.055,'bass');[12,16,19].forEach((interval,j)=>tone(music,i*4+.15+j*.16,3.5,hz(base+interval),.025));});
  bank.music=music;
  const cooking=canvas(4);noise(cooking,.018);for(let i=0;i<cooking.length;i++)cooking[i]*=.5+.5*Math.sin(Math.PI*i/cooking.length)**2;bank.cooking=cooking;
  return Object.fromEntries(Object.entries(bank).map(([name, samples])=>[name,encode(samples,name==='music'?.38:.65)]));
}
function generate() {
  const out=path.resolve(__dirname,'..','assets','audio');fs.mkdirSync(out,{recursive:true});const bank=sounds();
  for(const [name,data] of Object.entries(bank))fs.writeFileSync(path.join(out,`${name}.wav`),data);
  // Embedded bank avoids fetch/CORS restrictions when index.html is opened via file://.
  fs.writeFileSync(path.join(out,'bank.js'),'/* Generated by scripts/synthesize-audio.cjs. Original local PCM audio. */\nwindow.BaiweiAudioBank = '+JSON.stringify(Object.fromEntries(Object.entries(bank).map(([k,v])=>[k,v.toString('base64')])))+';\n');
  console.log(`音效合成完成：${Object.keys(bank).length}个22.05kHz单声道PCM WAV，含24秒原创循环配乐和离线音频库。`);
}
if(require.main===module)generate();
